def light_mesh(kind: int):
    """(vertices, indices) of light shaft `kind`; kind 1 is kind 0 mirrored, like the game."""
    m = LIGHT.get(kind, LIGHT[0])
    v = m["v"]
    if kind == 1:
        v = tuple((-x, y, u, w, a) for x, y, u, w, a in v)
    return v, m["i"]


def mesh_for(params):
    """(texture name, vertices, indices) a type-70 / 71 / 72 record draws, or None."""
    tid = params[0] & 0xFFFF
    kind = params[8] if len(params) > 8 else 0
    if tid == 70:
        v, i = light_mesh(kind)
        return LIGHT_TEXTURE, v, i
    if tid == 71:
        m = WATER.get(kind, WATER[0])
        return WATER_TEXTURE, m["v"], m["i"]
    if tid == 72:
        return ROOM_TEXTURES[1 if kind == 1 else 0], ROOM["v"], ROOM["i"]
    return None


def rasterize(tex, verts, tris, px_per_unit: float = 3.0, mirror: bool = False):
    """Draw a textured mesh: `tex` is the RGBA texture as stored (un-rotated), UVs wrap
    (repeat, or with `mirror` every other tile flipped, like wrap mode 3), and
    each vertex's intensity scales the alpha. Returns (RGBA image, quad) with the quad
    (x0, y0, x1, y1) in sprite pixels around the object (3 per sub-unit, as spritequad), or
    None without numpy."""
    try:
        import numpy as np
    except ImportError:
        return None
    from PIL import Image
    xs = [v[0] for v in verts]
    ys = [v[1] for v in verts]
    x0, y0 = min(xs), min(ys)
    W = max(1, int(round((max(xs) - x0) * px_per_unit)))
    H = max(1, int(round((max(ys) - y0) * px_per_unit)))
    T = np.asarray(tex.convert("RGBA"), dtype=np.float32)
    th, tw = T.shape[:2]
    out = np.zeros((H, W, 4), dtype=np.float32)
    for a, b, c in zip(tris[0::3], tris[1::3], tris[2::3]):
        tri = (verts[a], verts[b], verts[c])
        P = np.array([[(v[0] - x0) * px_per_unit, (v[1] - y0) * px_per_unit] for v in tri])
        bx0, by0 = np.floor(P.min(0)).astype(int)
        bx1, by1 = np.ceil(P.max(0)).astype(int)
        bx0, by0, bx1, by1 = max(bx0, 0), max(by0, 0), min(bx1, W - 1), min(by1, H - 1)
        if bx1 < bx0 or by1 < by0:
            continue
        (ax, ay), (qx, qy), (cx, cy) = P
        d = (qy - cy) * (ax - cx) + (cx - qx) * (ay - cy)
        if abs(d) < 1e-9:
            continue
        # barycentrics as row + column terms (broadcast, no full-box coordinate grids), then
        # everything else only for the pixels inside the triangle -- the thin diagonal
        # light-shaft triangles cover a small part of their boxes
        gx = np.arange(bx0, bx1 + 1, dtype=np.float64) + 0.5
        gy = np.arange(by0, by1 + 1, dtype=np.float64) + 0.5
        l0 = ((qy - cy) * (gx - cx)[None, :] + (cx - qx) * (gy - cy)[:, None]) / d
        l1 = ((cy - ay) * (gx - cx)[None, :] + (ax - cx) * (gy - cy)[:, None]) / d
        inside = (l0 >= -1e-6) & (l1 >= -1e-6) & (1 - l0 - l1 >= -1e-6)
        iy, ix = np.nonzero(inside)
        if not len(iy):
            continue
        l0, l1 = l0[iy, ix], l1[iy, ix]
        l2 = 1 - l0 - l1
        u = l0 * tri[0][2] + l1 * tri[1][2] + l2 * tri[2][2]
        w = l0 * tri[0][3] + l1 * tri[1][3] + l2 * tri[2][3]
        if mirror:                          # 0..1..2 -> 0..1..0, repeating
            u, w = 1 - np.abs((u % 2.0) - 1), 1 - np.abs((w % 2.0) - 1)
        else:
            u, w = u % 1.0, w % 1.0
        k = (l0 * tri[0][4] + l1 * tri[1][4] + l2 * tri[2][4]).clip(0, 1)
        # v counts from the BOTTOM row of the stored image (the GL convention; spritequad's
        # TextureCoordinator crop works the same way) -- from the top drew the hall upside down
        px = T[((1.0 - w) * th).astype(int).clip(0, th - 1), (u * tw).astype(int).clip(0, tw - 1)]
        alpha = px[:, 3] * k
        oy, ox = iy + by0, ix + bx0
        sa = (alpha / 255.0)[:, None]
        out[oy, ox, :3] = out[oy, ox, :3] * (1 - sa) + px[:, :3] * sa
        out[oy, ox, 3] = np.maximum(out[oy, ox, 3], alpha)
    img = Image.fromarray(out.clip(0, 255).astype(np.uint8), "RGBA")
    return img, (x0 * 3, y0 * 3, max(xs) * 3, max(ys) * 3)


# Bump when rasterize() changes what it draws: every cached image is then redrawn.
RASTER_VERSION = 2


def mesh_quad(verts):
    """The (x0, y0, x1, y1) sprite-pixel quad rasterize() gives these vertices."""
    xs = [v[0] for v in verts]
    ys = [v[1] for v in verts]
    return min(xs) * 3, min(ys) * 3, max(xs) * 3, max(ys) * 3


def rasterize_cached(tex_data: bytes, verts, tris, mirror: bool = False, cache_dir=None):
    """rasterize() for a texture file's bytes, remembered on disk: the image is kept as a
    PNG in `cache_dir` (the toolkit's cache/meshes by default) under a hash of the texture
    bytes, the mesh and RASTER_VERSION, so a change to any of them draws it afresh. The
    first call costs a rasterize (about a second for the palace hall); later ones a PNG
    load. Returns (RGBA image, quad) or None (no numpy, undecodable texture)."""
    import hashlib
    from PIL import Image
    from . import texture
    if cache_dir is None:
        from .gamepaths import TOOLKIT
        cache_dir = TOOLKIT / "cache" / "meshes"
    h = hashlib.sha1()
    h.update(b"v%d|%d|" % (RASTER_VERSION, bool(mirror)))
    h.update(tex_data)
    h.update(repr((tuple(tuple(v) for v in verts), tuple(tris))).encode())
    path = cache_dir / (h.hexdigest() + ".png")
    quad = mesh_quad(verts)
    try:
        if path.is_file():
            with Image.open(path) as im:
                return im.convert("RGBA"), quad
    except Exception:
        pass                                # a damaged file: draw it again
    tex = texture.decode_to_image(tex_data, rotate=False)
    if tex is None:
        return None
    got = rasterize(tex, verts, tris, mirror=mirror)
    if got is None:
        return None
    try:
        cache_dir.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".tmp")
        got[0].save(tmp, "PNG", compress_level=1)
        tmp.replace(path)
    except OSError:
        pass                                # read-only toolkit folder: just don't keep it
    return got
