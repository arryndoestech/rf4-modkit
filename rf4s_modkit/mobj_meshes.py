def light_mesh(kind: int):
    """(vertices, indices) of light shaft `kind`; kind 1 is kind 0 mirrored, like the game."""
    m = LIGHT.get(kind, LIGHT[0])
    v = m["v"]
    if kind == 1:
        v = tuple((-x, y, u, w, a) for x, y, u, w, a in v)
    return v, m["i"]


def mesh_for(params):
    """(texture name, vertices, indices) a type-70 / 72 record draws, or None."""
    tid = params[0] & 0xFFFF
    kind = params[8] if len(params) > 8 else 0
    if tid == 70:
        v, i = light_mesh(kind)
        return LIGHT_TEXTURE, v, i
    if tid == 72:
        return ROOM_TEXTURES[1 if kind == 1 else 0], ROOM["v"], ROOM["i"]
    return None


def rasterize(tex, verts, tris, px_per_unit: float = 3.0):
    """Draw a textured mesh: `tex` is the RGBA texture as stored (un-rotated), UVs wrap, and
    each vertex's intensity scales the alpha. Returns (RGBA image, quad) with the quad
    (x0, y0, x1, y1) in sprite pixels around the object (3 per sub-unit, as spritequad), or
    None without numpy."""
    try:
        import numpy as np
    except ImportError:
        return None
    from PIL import Image
    xs = [v[0] for v in verts]
    ys = [v[1] for v in verts]
    x0, y0 = min(xs), min(ys)
    W = max(1, int(round((max(xs) - x0) * px_per_unit)))
    H = max(1, int(round((max(ys) - y0) * px_per_unit)))
    T = np.asarray(tex.convert("RGBA"), dtype=np.float32)
    th, tw = T.shape[:2]
    out = np.zeros((H, W, 4), dtype=np.float32)
    for a, b, c in zip(tris[0::3], tris[1::3], tris[2::3]):
        tri = (verts[a], verts[b], verts[c])
        P = np.array([[(v[0] - x0) * px_per_unit, (v[1] - y0) * px_per_unit] for v in tri])
        bx0, by0 = np.floor(P.min(0)).astype(int)
        bx1, by1 = np.ceil(P.max(0)).astype(int)
        bx0, by0, bx1, by1 = max(bx0, 0), max(by0, 0), min(bx1, W - 1), min(by1, H - 1)
        if bx1 < bx0 or by1 < by0:
            continue
        (ax, ay), (qx, qy), (cx, cy) = P
        d = (qy - cy) * (ax - cx) + (cx - qx) * (ay - cy)
        if abs(d) < 1e-9:
            continue
        gy, gx = np.mgrid[by0:by1 + 1, bx0:bx1 + 1] + 0.5
        l0 = ((qy - cy) * (gx - cx) + (cx - qx) * (gy - cy)) / d
        l1 = ((cy - ay) * (gx - cx) + (ax - cx) * (gy - cy)) / d
        l2 = 1 - l0 - l1
        inside = (l0 >= -1e-6) & (l1 >= -1e-6) & (l2 >= -1e-6)
        if not inside.any():
            continue
        u = (l0 * tri[0][2] + l1 * tri[1][2] + l2 * tri[2][2]) % 1.0
        w = (l0 * tri[0][3] + l1 * tri[1][3] + l2 * tri[2][3]) % 1.0
        k = (l0 * tri[0][4] + l1 * tri[1][4] + l2 * tri[2][4]).clip(0, 1)
        px = T[(w * th).astype(int).clip(0, th - 1), (u * tw).astype(int).clip(0, tw - 1)]
        alpha = px[..., 3] * k * inside
        reg = out[by0:by1 + 1, bx0:bx1 + 1]
        sa = alpha[..., None] / 255.0
        reg[..., :3] = reg[..., :3] * (1 - sa) + px[..., :3] * sa
        reg[..., 3] = np.maximum(reg[..., 3], alpha)
    img = Image.fromarray(out.clip(0, 255).astype(np.uint8), "RGBA")
    return img, (x0 * 3, y0 * 3, max(xs) * 3, max(ys) * 3)
