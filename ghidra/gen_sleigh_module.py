#!/usr/bin/env python3
"""Generate the RF4MC Ghidra processor module (SLEIGH) from the audited opcode table.

Emits a complete language module into ghidra/RF4MC/ (and optionally copies it into a
Ghidra installation's Ghidra/Processors/ directory), so rf3.mc imports with language
`RF4MC:LE:32:default` and the script bytecode DISASSEMBLES into real instructions:
named mnemonics straight from rf4s_modkit.opcode_meta, operand lists, and native
control flow (CALL/JMP/branches produce Ghidra flow + xrefs by themselves).

Model (matches docs/script_vm.md and the shipped-corpus statement sizes):
  action op   [op16][cnt16][cnt16 x u16]   named per op; argc<=16 inlined, argc>16
                                           renders header-only with no fall-through
                                           (the apply script types the tail as data)
  0xFFFF RET            2  return
  0xFFF1 FRAME n        4  fall-through (frame setup)
  0xFFFE CALL t         4  call bankbase+t
  0xFFFA JMP t          4  goto bankbase+t
  0xFFFB STORE e        4  fall-through
  0xFFFD BR_RET e       4  conditional return
  0xFFFC DIALOG id32    6  fall-through
  0xFFF8/9 BR_Z/BR_NZ   6  cbranch bankbase+t
  0xFFF7/6 SWITCH_EQ/GE 6  header (expr,n), indirect-jump flow (table = data tail)
  0xFFF5/4 PROMPT_*     4  header (n), indirect-jump flow (table = data tail)
  0xFFF3/2 JMP_IND/RAND_BR 4  header (n), indirect-jump flow

Bank-local u16 targets resolve through the `bankbase` context register, which the
apply script sets over each bank's byte range before disassembling.

Usage (from tools/modding):
    python ghidra/gen_sleigh_module.py                     # write ghidra/RF4MC/
    python ghidra/gen_sleigh_module.py --install "C:/Users/arryn/ghidra_12.1.2_PUBLIC"
"""
from __future__ import annotations

import argparse
import pathlib
import re
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from rf4s_modkit import opcode_meta as M     # noqa: E402

MAX_INLINE_ARGS = 16


def mnemonic(op):
    m = M.META.get(op, {}).get("m") or ""
    m = re.sub(r"[^A-Za-z0-9_]", "", m)
    if not m or not re.match(r"^[A-Za-z_]", m):
        return "op%d" % op
    return m


CORE = r"""# RF4MC — Rune Factory 4 Special cutscene script VM (rf3.mc MYCF bytecode).
# GENERATED by tools/modding/ghidra/gen_sleigh_module.py — edit the generator, not this.
define endian=little;
define alignment=2;

define space ram type=ram_space size=4 default;
define space register type=register_space size=4;

define register offset=0 size=4 [ pc sp r0 ];

# bankbase: the containing bank's file offset — bytecode targets are bank-local u16
# offsets, so real addresses are bankbase+target. Set per bank range by the apply
# script (ApplyRF4Cutscenes.java) before disassembly.
define register offset=0x40 size=8 ctxreg;
define context ctxreg
  bankbase=(0,31) noflow
;

define token opw (16) op16=(0,15) oplow=(0,9) ophi=(10,15);
define token cw  (16) cnt16=(0,15) cntchk=(0,15);
define token aw  (16) a16=(0,15);
define token dw  (32) d32=(0,31);

# a bank-local branch/call target -> absolute address
dest: reloc is a16 [ reloc = bankbase + a16; ] { export *[ram]:4 reloc; }

@include "rf4mc_args.sinc"

# ---- control opcodes ----------------------------------------------------------------
:RET is op16=0xffff { tmp:4=0; return [tmp]; }
:FRAME cnt16 is op16=0xfff1; cnt16 { }
:CALL dest is op16=0xfffe; dest { call dest; }
:JMP dest is op16=0xfffa; dest { goto dest; }
:STORE a16 is op16=0xfffb; a16 { }
:BR_RET a16 is op16=0xfffd; a16 { if (r0 == 0) goto <skip>; tmp:4=0; return [tmp]; <skip> }
:DIALOG d32 is op16=0xfffc; d32 { }
:BR_Z a16,dest is op16=0xfff8; a16; dest { if (r0 == 0) goto dest; }
:BR_NZ a16,dest is op16=0xfff9; a16; dest { if (r0 != 0) goto dest; }
:SWITCH_EQ a16,cnt16 is op16=0xfff7; a16; cnt16 { tmp:4=0; goto [tmp]; }
:SWITCH_GE a16,cnt16 is op16=0xfff6; a16; cnt16 { tmp:4=0; goto [tmp]; }
:PROMPT_CHOICE_FORCED cnt16 is op16=0xfff5; cnt16 { tmp:4=0; goto [tmp]; }
:PROMPT_CHOICE cnt16 is op16=0xfff4; cnt16 { tmp:4=0; goto [tmp]; }
:JMP_IND cnt16 is op16=0xfff3; cnt16 { tmp:4=0; goto [tmp]; }
:RAND_BR cnt16 is op16=0xfff2; cnt16 { tmp:4=0; goto [tmp]; }

@include "rf4mc_ops.sinc"

# ---- action opcodes: two constructors for ALL 763 ops -------------------------------
# The mnemonic comes from the name list attached to oplow (10-bit op number); real
# action ops all have ophi=0. This keeps the root table tiny — one constructor per
# op made the compiler's O(n^2) pattern-conflict pass explode.
:^oplow args is ophi=0 & oplow; cntchk<0x11 ... & args { }
:^oplow bigargs is ophi=0 & oplow; cntchk>0x10 & bigargs { tmp:4=0; goto [tmp]; }
"""

LDEFS = """<?xml version="1.0" encoding="UTF-8"?>
<language_definitions>
   <language processor="RF4MC"
             endian="little"
             size="32"
             variant="default"
             version="1.0"
             slafile="rf4mc.sla"
             processorspec="rf4mc.pspec"
             id="RF4MC:LE:32:default">
      <description>Rune Factory 4 Special cutscene script VM (rf3.mc MYCF bytecode)</description>
      <compiler name="default" spec="rf4mc.cspec" id="default"/>
   </language>
</language_definitions>
"""

PSPEC = """<?xml version="1.0" encoding="UTF-8"?>
<processor_spec>
  <programcounter register="pc"/>
</processor_spec>
"""

CSPEC = """<?xml version="1.0" encoding="UTF-8"?>
<compiler_spec>
  <data_organization>
    <pointer_size value="4" />
  </data_organization>
  <global>
    <range space="ram"/>
  </global>
  <stackpointer register="sp" space="ram" growth="negative"/>
  <default_proto>
    <prototype name="__stdcall" extrapop="0" stackshift="0">
      <input>
        <pentry maxsize="4" minsize="1"><register name="r0"/></pentry>
      </input>
      <output>
        <pentry maxsize="4" minsize="1"><register name="r0"/></pentry>
      </output>
    </prototype>
  </default_proto>
</compiler_spec>
"""


def gen_args():
    """Non-recursive counted operand list: 16 positional arg tokens (all u16 fields
    on identical 2-byte tokens) + one `args` alternative per argc 0..MAX_INLINE.
    bigargs matches everything larger (header-only)."""
    L = ["# Counted operand list (expression-pool offsets, u16 each) - fixed",
         "# constructors per argc; SLEIGH recursion is avoided on purpose (a",
         "# context-counted recursive table hangs the 12.1.2 compiler)."]
    for i in range(1, MAX_INLINE_ARGS + 1):
        L.append("define token awt%d (16) arg%d=(0,15);" % (i, i))
    L.append("args: is cnt16=0 { }")
    for n in range(1, MAX_INLINE_ARGS + 1):
        disp = ",".join("arg%d" % i for i in range(1, n + 1))
        pat = "; ".join(["cnt16=%d" % n] + ["arg%d" % i for i in range(1, n + 1)])
        L.append("args: %s is %s { }" % (disp, pat))
    L.append('bigargs: "argc="^cnt16 is cnt16 { }')
    return "\n".join(L) + "\n"


def gen_ops():
    lines = ["# Mnemonic table for the 10-bit action-op field (763 real ops from the",
             "# audited rf4s_modkit.opcode_meta table; 763..1023 are unreachable filler).",
             "attach names [ oplow ] ["]
    for op in range(1024):
        m = mnemonic(op) if op < 763 else "op%d" % op
        lines.append('  "%s"' % m)
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--install", help="Ghidra install dir to copy the module into")
    a = ap.parse_args()
    out = HERE / "RF4MC" / "data" / "languages"
    out.mkdir(parents=True, exist_ok=True)
    (HERE / "RF4MC" / "Module.manifest").write_text("", encoding="utf-8")
    (out / "rf4mc.slaspec").write_text(CORE, encoding="utf-8")
    (out / "rf4mc_ops.sinc").write_text(gen_ops(), encoding="utf-8")
    (out / "rf4mc_args.sinc").write_text(gen_args(), encoding="utf-8")
    (out / "rf4mc.ldefs").write_text(LDEFS, encoding="utf-8")
    (out / "rf4mc.pspec").write_text(PSPEC, encoding="utf-8")
    (out / "rf4mc.cspec").write_text(CSPEC, encoding="utf-8")
    print("wrote", out)
    if a.install:
        dst = pathlib.Path(a.install) / "Ghidra" / "Processors" / "RF4MC"
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(HERE / "RF4MC", dst)
        print("installed to", dst)


if __name__ == "__main__":
    main()
